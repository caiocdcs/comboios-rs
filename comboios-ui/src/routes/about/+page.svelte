  <h1 class="text-2xl font-extrabold tracking-tight mb-3">About Comboios</h1>

  <p class="mb-6">
    Live departures, arrivals and delays for trains in Portugal: when your train leaves, from which
    platform, and how late it's running.
  </p>

  <h2 class="text-lg font-bold mb-2">Using it</h2>
  <ul class="list-disc pl-5 space-y-1.5 mb-6">
    <li>Search for a station, or pick one of the main stations on the home screen.</li>
    <li>Tap the star on a station's board to keep it at the top of the home screen.</li>
    <li>Tap a train to follow it stop by stop, with its next stop, platform and expected arrival.</li>
    <li>Boards update every minute and trains every 30 seconds while the app is open.</li>
  </ul>

  <h2 class="text-lg font-bold mb-2">Add it to your phone</h2>
  <p class="mb-6">
    On iPhone, open the Share menu in Safari and choose <strong class="font-semibold">Add to Home Screen</strong>.
    On Android, open the Chrome menu and choose <strong class="font-semibold">Install app</strong>.
    It then opens full screen, and still shows the last boards you loaded when you lose signal.
  </p>

  <h2 class="text-lg font-bold mb-2">Where the times come from</h2>
  <p class="mb-6">
    Timetables, delays and platforms come from the public websites of Comboios de Portugal (CP) and
    Infraestruturas de Portugal (IP). Platforms appear once the station announces them.
  </p>

  <p class="text-sm text-gray-500 dark:text-gray-400 border-t border-gray-200 dark:border-gray-700 pt-4">
    This is an unofficial app, not affiliated with CP or IP. Check station announcements before you travel.
  </p>
